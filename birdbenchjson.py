# ===== QUALITY & SAFETY LIMITS =====
MAX_DEPTH = 2        # Good structure, no explosion
MAX_ROWS  = 3000     # Enough samples per table
DB_TIME_LIMIT = 90   # Seconds per DB

def get_db_schema(db_path):
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()

    cursor.execute("SELECT name FROM sqlite_master WHERE type='table';")
    tables = [r[0] for r in cursor.fetchall() if r[0] != "sqlite_sequence"]

    fk_map = defaultdict(list)
    reverse_fk_map = defaultdict(list)

    for table in tables:
        try:
            cursor.execute(f"PRAGMA foreign_key_list('{table}')")
            for fk in cursor.fetchall():
                parent_table = fk[2]
                child_col = fk[3]
                parent_col = fk[4]
                if parent_table:
                    fk_map[table].append((child_col, parent_table, parent_col))
                    reverse_fk_map[parent_table].append((parent_col, table, child_col))
        except sqlite3.OperationalError:
            pass

    conn.close()
    return tables, fk_map, reverse_fk_map

def find_clusters(tables, fk_map):
    adj = defaultdict(set)
    for table in tables:
        for _, parent, _ in fk_map.get(table, []):
            adj[table].add(parent)
            adj[parent].add(table)

    visited = set()
    clusters = []

    for table in tables:
        if table not in visited:
            stack = [table]
            cluster = set()
            while stack:
                node = stack.pop()
                if node not in visited:
                    visited.add(node)
                    cluster.add(node)
                    stack.extend(adj[node])
            clusters.append(list(cluster))
    return clusters


def get_main_table(cluster, fk_map):
    candidates = []
    for table in cluster:
        points_out = any(parent in cluster for _, parent, _ in fk_map.get(table, []))
        if not points_out:
            candidates.append(table)
    return candidates[0] if candidates else None

def recursive_embed(conn, current_table, current_row, reverse_fk_map, cluster_set, depth=0):
    if depth >= MAX_DEPTH:
        return dict(current_row)

    document = dict(current_row)

    for parent_col, child_table, child_fk_col in reverse_fk_map.get(current_table, []):
        if child_table not in cluster_set:
            continue

        if parent_col not in document or document[parent_col] is None:
            continue

        pk_value = document[parent_col]
        cursor = conn.execute(
            f'SELECT * FROM "{child_table}" WHERE "{child_fk_col}" = ?',
            (pk_value,)
        )

        cols = [d[0] for d in cursor.description]
        children = []

        for row in cursor:
            row_dict = dict(zip(cols, row))
            children.append(
                recursive_embed(
                    conn,
                    child_table,
                    row_dict,
                    reverse_fk_map,
                    cluster_set,
                    depth + 1
                )
            )

        if children:
            document[child_table] = children

    return document

def process_single_db(db_path):
    tables, fk_map, reverse_fk_map = get_db_schema(db_path)
    clusters = find_clusters(tables, fk_map)

    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row

    nosql_db = {}

    for cluster in clusters:
        main_table = get_main_table(cluster, fk_map)
        if not main_table:
            continue

        cursor = conn.execute(
            f'SELECT * FROM "{main_table}" LIMIT {MAX_ROWS}'
        )

        cols = [d[0] for d in cursor.description]
        cluster_set = set(cluster)
        docs = []

        for row in cursor:
            row_dict = dict(zip(cols, row))
            docs.append(
                recursive_embed(
                    conn,
                    main_table,
                    row_dict,
                    reverse_fk_map,
                    cluster_set
                )
            )

        if docs:
            nosql_db[main_table] = docs

    conn.close()
    return nosql_db

def run_pipeline():
    base_dir = "./bird_dataset"
    output_dir = "./bird_nosql_output"
    os.makedirs(output_dir, exist_ok=True)

    for mode in ["train", "dev"]:
        search_path = os.path.join(base_dir, f"{mode}_databases")
        if not os.path.exists(search_path):
            print(f"Skipping {mode}")
            continue

        db_files = []
        for root, _, files in os.walk(search_path):
            for f in files:
                if f.endswith(".sqlite"):
                    db_files.append(os.path.join(root, f))

        print(f"\nProcessing {mode.upper()} ({len(db_files)} DBs)")

        for db_path in tqdm(db_files):
            db_name = os.path.basename(db_path).replace(".sqlite", "")

            print(f"\n→ DB: {db_name}")
            start = time.time()

            try:
                data = process_single_db(db_path)
            except Exception as e:
                print(f"❌ Failed DB {db_name}: {e}")
                continue

            #if time.time() - start > DB_TIME_LIMIT:
            #    print(f"⏭️ Timed out DB: {db_name}")
            #    continue

            out_file = os.path.join(output_dir, f"{mode}_{db_name}.json")
            with open(out_file, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2, default=str)

    print("\n✅ Conversion finished successfully.")

run_pipeline()

